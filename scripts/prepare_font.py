"""Build the embedded Chinese UI font from the OFL-licensed Noto Sans SC source."""
import argparse
import json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
parser.add_argument("--output", type=Path)
parser.add_argument("--extra-text", type=Path, help="Optional private catalogue names to embed on MCU")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
glyphs_path = root / "core/ui/runtime-glyphs.slint"
text = "".join(p.read_text(encoding="utf-8") for directory in ("core/ui", "core/src", "shared/src", "core/data")
               for p in (root / directory).rglob("*")
               if p.suffix in (".slint", ".rs", ".json", ".csv") and p != glyphs_path)
characters = set(chr(c) for c in range(32, 127))
if args.extra_text:
    text += args.extra_text.read_text(encoding="utf-8")
# GB2312 level one covers 3,755 common Chinese characters, including user names.
# Add source/private characters on top instead of relying on observed names alone.
for lead in range(0xB0,0xD8):
    for trail in range(0xA1,0xFF):
        try: characters.update(bytes([lead,trail]).decode('gb2312'))
        except UnicodeDecodeError: pass
characters.update(c for c in text if ord(c) >= 160)
font = TTFont(args.font)
if "fvar" in font:
    font = instantiateVariableFont(font, {"wght": 500}, inplace=True)
# The upstream variable font's default family is Thin. Give the subset its own
# family and PostScript name so both desktop and MCU resolve the same font.
for name_id, value in {1: "Console Sans", 2: "Medium", 4: "Console Sans Medium", 6: "ConsoleSans-Medium"}.items():
    for record in font["name"].names:
        if record.nameID == name_id:
            record.string = value.encode(record.getEncoding())
available=set(font.getBestCmap())
missing={c for c in characters if ord(c) not in available}
characters={c for c in characters if ord(c) in available}
options = subset.Options()
options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
subsetter = subset.Subsetter(options=options)
subsetter.populate(text="".join(sorted(characters)))
subsetter.subset(font)
output = args.output or root / "core/ui/fonts/ConsoleSans.ttf"
output.parent.mkdir(parents=True, exist_ok=True)
font.save(output)
# Slint's software renderer embeds glyphs from Slint literals only. Rust log
# messages and CSV catalog names need an explicitly referenced Slint literal too.
coverage = "".join(sorted(c for c in characters if c.isprintable()))
(root/'core/ui/fonts/coverage.txt').write_text(coverage,encoding='utf-8',newline='')
glyphs_path.write_text(
    "// Generated by scripts/prepare_font.py; includes runtime Rust/data text.\n"
    "export global RuntimeGlyphs {\n"
    "    out property <string> characters: " + json.dumps(coverage, ensure_ascii=False) + ";\n}\n",
    encoding="utf-8", newline="\n")
print(f"UI font: {len(characters)} supported characters, {output.stat().st_size} bytes; {len(missing)} unsupported source symbols excluded")
